#!/usr/bin/env python3
"""Fixture tests for scripts/doctor.py.

Every case runs the real doctor script against a scratch checkout with a
controlled PATH and fake executables. Nothing installs a tool, reads the host's
toolchain, executes a hook, or touches the network. Run locally with
`just test-doctor` and in CI's `changes` job.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOCTOR = REPO / "scripts" / "doctor.py"
DEV_TOOLS = REPO / "scripts" / "dev-tools.sh"
RUST_VERSION = "1.60.0"
JUST_VERSION = "1.30.0"


def dev_tool_pins() -> list[tuple[str, str]]:
    text = DEV_TOOLS.read_text(encoding="utf-8")
    return re.findall(r"^(?:pins=')?cargo install (\S+) --version (\S+) --locked$", text, re.M)


def binary_for(package: str) -> str:
    return {"cargo-edit": "cargo-add", "cocogitto": "cog"}.get(package, package)


class Fixture:
    def __init__(self, base: Path):
        self.root = base / "repo"
        self.scripts = self.root / "scripts"
        self.bin = self.root / "fake-bin"
        self.cargo_home = self.root / "cargo-home"
        self.list_dir = self.root / "install-list"
        self.state = self.root / "state"
        self.hooks = self.root / ".git" / "hooks"
        for path in (self.scripts, self.bin, self.cargo_home / "bin", self.list_dir, self.state, self.hooks):
            path.mkdir(parents=True, exist_ok=True)

        shutil.copy2(DOCTOR, self.scripts / "doctor.py")
        shutil.copy2(DEV_TOOLS, self.scripts / "dev-tools.sh")
        (self.scripts / "doctor.py").chmod(0o755)
        (self.scripts / "dev-tools.sh").chmod(0o755)

        (self.root / "rust-toolchain.toml").write_text(
            f'[toolchain]\nchannel = "{RUST_VERSION}"\ncomponents = ["clippy", "rustfmt", "rust-analyzer"]\n',
            encoding="utf-8",
        )
        (self.root / ".mise.toml").write_text(
            f'[tools]\nrust = {{ version = "{RUST_VERSION}", components = ["clippy", "rustfmt", "rust-analyzer"] }}\n'
            f'just = "{JUST_VERSION}"\nsccache = "0.17.0"\n\n[env]\nRUSTC_WRAPPER = "sccache"\n',
            encoding="utf-8",
        )

        for hook in ("pre-commit", "pre-push", "commit-msg"):
            path = self.hooks / hook
            path.write_text("#!/bin/sh\n# File generated by prek: fake fixture\n", encoding="utf-8")
            path.chmod(0o755)

        (self.state / "components").write_text(
            "clippy-aarch64-apple-darwin\nrustfmt-aarch64-apple-darwin\nrust-analyzer-aarch64-apple-darwin\n",
            encoding="utf-8",
        )
        (self.state / "targets").write_text("x86_64-unknown-linux-gnu\n", encoding="utf-8")

        self.seed_all_pins()
        self.write_tools()

    def write_exe(self, name: str, body: str) -> Path:
        path = self.bin / name
        path.write_text("#!/bin/sh\nset -eu\n" + body, encoding="utf-8")
        path.chmod(0o755)
        return path

    def write_tools(self) -> None:
        self.write_exe(
            "cargo",
            'if [ "${RUSTUP_AUTO_INSTALL:-}" != "0" ]; then echo "cargo fixture: auto-install guard missing" >&2; exit 99; fi\n'
            'case "${1:-}" in\n'
            '  --version) echo "cargo ${FAKE_RUST_VERSION} (fake)"; exit 0 ;;\n'
            "  install)\n"
            "    shift\n"
            '    if [ "${1:-}" = "--list" ]; then\n'
            '      for entry in "$FAKE_LIST_DIR"/*; do [ -e "$entry" ] && cat "$entry"; done\n'
            "      exit 0\n"
            "    fi\n"
            "    exit 1 ;;\n"
            "  bloat)\n"
            '    if [ "${FAKE_NO_BLOAT:-}" = "1" ]; then echo "error: no such command: bloat" >&2; exit 101; fi\n'
            '    echo "0.12.1"; exit 0 ;;\n'
            "  *) exit 2 ;;\n"
            "esac\n",
        )
        self.write_exe(
            "rustc",
            'if [ "${RUSTUP_AUTO_INSTALL:-}" != "0" ]; then echo "rustc fixture: auto-install guard missing" >&2; exit 99; fi\n'
            'if [ "${FAKE_BROKEN_RUSTC:-}" = "1" ]; then echo "simulated rustc failure" >&2; exit 1; fi\n'
            'echo "rustc ${FAKE_RUST_VERSION} (fake)"\n',
        )
        self.write_exe(
            "rustup",
            'case "$*" in\n'
            '  "component list --installed") cat "$FAKE_STATE_DIR/components" ;;\n'
            '  "target list --installed") cat "$FAKE_STATE_DIR/targets" ;;\n'
            "  *) exit 2 ;;\n"
            "esac\n",
        )
        self.write_exe("just", 'echo "just ${FAKE_JUST_VERSION}"\n')
        self.write_exe("python3", 'echo "Python 3.12.0"\n')
        self.write_exe(
            "git",
            'case "${1:-}" in\n'
            '  --version) echo "git version 2.40.0" ;;\n'
            '  rev-parse) [ "${2:-}" = "--git-path" ] && [ "${3:-}" = "hooks" ] && { echo "$FAKE_ROOT/.git/hooks"; exit 0; }; exit 2 ;;\n'
            "  *) exit 2 ;;\n"
            "esac\n",
        )
        self.write_exe("cc", 'echo "cc (fake) 1.0"\n')
        self.write_exe("mise", 'echo "2026.1.0 fake"\n')
        self.write_exe("samply", 'echo "samply 0.13.1"\n')
        self.write_exe(
            "xcrun",
            '[ "${1:-}" = "--find" ] && [ "${2:-}" = "xctrace" ] && { echo "/fake/xctrace"; exit 0; }; exit 1\n',
        )

    def seed_pin(self, package: str, version: str) -> None:
        binary = binary_for(package)
        (self.list_dir / package).write_text(f"{package} v{version}:\n    {binary}\n", encoding="utf-8")
        binary_path = self.cargo_home / "bin" / binary
        binary_path.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        binary_path.chmod(0o755)

    def seed_all_pins(self) -> None:
        for package, version in dev_tool_pins():
            self.seed_pin(package, version)

    def remove_pin(self, package: str) -> None:
        (self.list_dir / package).unlink(missing_ok=True)
        (self.cargo_home / "bin" / binary_for(package)).unlink(missing_ok=True)

    def environment(self, **overrides: str | None) -> dict[str, str]:
        environment = {
            "PATH": f"{self.bin}:/usr/bin:/bin",
            "CARGO_HOME": str(self.cargo_home),
            "FAKE_LIST_DIR": str(self.list_dir),
            "FAKE_STATE_DIR": str(self.state),
            "FAKE_ROOT": str(self.root),
            "FAKE_RUST_VERSION": RUST_VERSION,
            "FAKE_JUST_VERSION": JUST_VERSION,
        }
        for key, value in overrides.items():
            if value is None:
                environment.pop(key, None)
            else:
                environment[key] = value
        return environment

    def run(self, *args: str, **env: str | None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(self.scripts / "doctor.py"), *args],
            cwd=str(self.root),
            env=self.environment(**env),
            capture_output=True,
            text=True,
            check=False,
        )


class DoctorTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory(prefix="doctor-test.")
        self.fixture = Fixture(Path(self.temp.name))

    def tearDown(self) -> None:
        self.temp.cleanup()

    def run_doctor(self, *args: str, **env: str | None) -> subprocess.CompletedProcess[str]:
        return self.fixture.run(*args, **env)

    def output(self, result: subprocess.CompletedProcess[str]) -> str:
        return result.stdout + result.stderr

    def json_report(self, *args: str, **env: str | None) -> dict:
        result = self.run_doctor("--json", *args, **env)
        self.assertIn(result.returncode, (0, 1), result.stdout + result.stderr)
        return json.loads(result.stdout)

    def check(self, report: dict, name: str) -> dict:
        for check in report["checks"]:
            if check["name"] == name:
                return check
        self.fail(f"report has no check named {name}: {[c['name'] for c in report['checks']]}")

    def test_healthy_environment_passes_with_human_and_json_reports(self) -> None:
        result = self.run_doctor()
        self.assertEqual(result.returncode, 0, self.output(result))
        self.assertIn("Cake developer readiness", result.stdout)
        self.assertIn("Baseline (just check):", result.stdout)
        self.assertIn("Full gate (just check-full):", result.stdout)
        self.assertIn("Git hooks:", result.stdout)
        self.assertIn("Optional capabilities:", result.stdout)
        self.assertIn("pre-commit hook installed", result.stdout)
        self.assertIn("Developer environment is ready.", result.stdout)

        report = self.json_report()
        self.assertTrue(report["ok"])
        self.assertEqual(report["scope"], "all")
        self.assertEqual(self.check(report, "rustc")["status"], "ok")
        self.assertEqual(self.check(report, "pre-commit")["status"], "ok")
        self.assertFalse([check for check in report["checks"] if check["severity"] == "error"])

    def test_missing_required_tool_fails_with_a_recovery_hint(self) -> None:
        (self.fixture.bin / "rustc").unlink()
        result = self.run_doctor()
        self.assertEqual(result.returncode, 1)
        self.assertIn("rustc not found", self.output(result))
        self.assertIn(f"rustup toolchain install {RUST_VERSION}", self.output(result))
        report = self.json_report()
        self.assertFalse(report["ok"])
        self.assertEqual(self.check(report, "rustc")["status"], "missing")
        self.assertEqual(self.check(report, "rustc")["severity"], "error")

    def test_broken_required_tool_reports_the_command_failure(self) -> None:
        result = self.run_doctor(FAKE_BROKEN_RUSTC="1")
        self.assertEqual(result.returncode, 1)
        self.assertIn("simulated rustc failure", self.output(result))
        report = self.json_report(FAKE_BROKEN_RUSTC="1")
        self.assertEqual(self.check(report, "rustc")["status"], "broken")

    def test_wrong_rust_version_fails(self) -> None:
        result = self.run_doctor(FAKE_RUST_VERSION="1.59.0")
        self.assertEqual(result.returncode, 1)
        self.assertIn("rustc 1.59.0 (pinned 1.60.0)", self.output(result))
        report = self.json_report(FAKE_RUST_VERSION="1.59.0")
        self.assertEqual(self.check(report, "rustc")["status"], "version-mismatch")

    def test_mise_and_toolchain_pin_drift_fails(self) -> None:
        mise = self.fixture.root / ".mise.toml"
        mise.write_text(
            mise.read_text(encoding="utf-8").replace('version = "1.60.0"', 'version = "1.61.0"'),
            encoding="utf-8",
        )
        result = self.run_doctor()
        self.assertEqual(result.returncode, 1)
        self.assertIn(".mise.toml pins Rust 1.61.0, but rust-toolchain.toml pins 1.60.0", self.output(result))
        report = self.json_report()
        self.assertEqual(self.check(report, "toolchain pins")["status"], "broken")

    def test_newer_just_warns_but_does_not_fail_readiness(self) -> None:
        result = self.run_doctor(FAKE_JUST_VERSION="1.31.0")
        self.assertEqual(result.returncode, 0, self.output(result))
        self.assertIn("newer than pin", self.output(result))
        report = self.json_report(FAKE_JUST_VERSION="1.31.0")
        self.assertTrue(report["ok"])
        just = self.check(report, "just")
        self.assertEqual(just["status"], "newer")
        self.assertEqual(just["severity"], "warning")

    def test_older_just_fails_readiness(self) -> None:
        result = self.run_doctor(FAKE_JUST_VERSION="1.29.0")
        self.assertEqual(result.returncode, 1)
        self.assertIn("just 1.29.0 (pinned 1.30.0)", self.output(result))
        report = self.json_report(FAKE_JUST_VERSION="1.29.0")
        self.assertEqual(self.check(report, "just")["status"], "version-mismatch")

    def test_missing_pinned_tool_names_its_install_command(self) -> None:
        self.fixture.remove_pin("cargo-deny")
        result = self.run_doctor()
        self.assertEqual(result.returncode, 1)
        self.assertIn("cargo-deny not found", self.output(result))
        self.assertIn("cargo install cargo-deny --version 0.20.2 --locked", self.output(result))
        report = self.json_report()
        self.assertFalse(report["ok"])
        self.assertEqual(self.check(report, "cargo-deny")["status"], "missing")
        self.assertEqual(self.check(report, "cargo-deny")["severity"], "error")

    def test_missing_optional_pin_warns_without_failing(self) -> None:
        self.fixture.remove_pin("cargo-insta")
        result = self.run_doctor()
        self.assertEqual(result.returncode, 0, self.output(result))
        self.assertIn("cargo-insta not found", self.output(result))
        report = self.json_report()
        self.assertTrue(report["ok"])
        insta = self.check(report, "cargo-insta")
        self.assertFalse(insta["required"])
        self.assertEqual(insta["severity"], "warning")

    def test_missing_rust_component_fails_with_component_hint(self) -> None:
        (self.fixture.state / "components").write_text("rustfmt-aarch64-apple-darwin\n", encoding="utf-8")
        result = self.run_doctor()
        self.assertEqual(result.returncode, 1)
        self.assertIn("clippy component not installed", self.output(result))
        self.assertIn("rustup component add clippy", self.output(result))

    def test_missing_hook_fails_setup_postconditions(self) -> None:
        (self.fixture.hooks / "pre-push").unlink()
        result = self.run_doctor("--scope", "setup", "--quiet")
        self.assertEqual(result.returncode, 1)
        self.assertIn("pre-push hook missing", result.stderr)

        report = self.json_report("--scope", "setup")
        self.assertFalse(report["ok"])
        self.assertEqual(self.check(report, "pre-push")["status"], "missing-hook")
        self.assertTrue(self.check(report, "pre-push")["required"])

    def test_setup_scope_ignores_toolchain_and_other_capabilities(self) -> None:
        (self.fixture.bin / "rustc").unlink()
        result = self.run_doctor("--scope", "setup", "--quiet", FAKE_JUST_VERSION="1.29.0")
        self.assertEqual(result.returncode, 0, self.output(result))
        report = self.json_report("--scope", "setup", FAKE_JUST_VERSION="1.29.0")
        self.assertTrue(report["ok"])
        self.assertNotIn("rustc", {check["name"] for check in report["checks"]})
        self.assertEqual(self.check(report, "cargo-crap")["status"], "ok")

    def test_optional_missing_tools_are_reported_but_do_not_fail(self) -> None:
        (self.fixture.bin / "samply").unlink()
        (self.fixture.bin / "mise").unlink()
        result = self.run_doctor()
        self.assertEqual(result.returncode, 0, self.output(result))
        self.assertIn("samply not found", self.output(result))
        self.assertIn("mise not found", self.output(result))
        report = self.json_report()
        self.assertTrue(report["ok"])
        self.assertEqual(self.check(report, "samply")["severity"], "warning")

    def test_active_sccache_missing_fails_the_baseline(self) -> None:
        result = self.run_doctor(RUSTC_WRAPPER="sccache")
        self.assertEqual(result.returncode, 1)
        self.assertIn("sccache not found", self.output(result))
        self.assertIn("unset RUSTC_WRAPPER", self.output(result))
        report = self.json_report(RUSTC_WRAPPER="sccache")
        sccache = self.check(report, "sccache")
        self.assertTrue(sccache["required"])
        self.assertEqual(sccache["severity"], "error")

    def test_active_sccache_version_mismatch_fails_the_baseline(self) -> None:
        sccache = self.fixture.write_exe("sccache", 'echo "sccache 0.16.0"\n')
        result = self.run_doctor(RUSTC_WRAPPER=str(sccache))
        self.assertEqual(result.returncode, 1)
        self.assertIn("sccache 0.16.0 (pinned 0.17.0)", self.output(result))

    def test_json_and_configuration_errors(self) -> None:
        self.assertEqual(self.run_doctor("--bogus").returncode, 2)
        (self.fixture.root / ".mise.toml").unlink()
        result = self.run_doctor("--json")
        self.assertEqual(result.returncode, 2)
        self.assertIn("cannot read", result.stderr)


if __name__ == "__main__":
    unittest.main()
